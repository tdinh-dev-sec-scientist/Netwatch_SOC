"""
Write docs/bench/results-cicids2018.md from NetWatch Bench runs.

    # 1. replay every engine on every pack (see the doc for the commands)
    # 2. tune each engine on dev with the same budget, score the holdouts
    # 3. python eval/cicids2018/bench_results.py --runs runs

Every number in the document comes from a scorecard.json under --runs, so
re-running the commands regenerates the document.
"""

import argparse
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))
sys.path.insert(0, ROOT)

from netwatch_bench import stats  # noqa: E402

ENGINES = [('netwatch', 'NetWatch'), ('suricata', 'Suricata + ET Open'),
           ('zeek', 'Zeek')]
HELD_OUT = ('holdout', 'holdout2')


def load(path):
    if not os.path.exists(path):
        return None
    with open(path, encoding='utf-8') as fh:
        return json.load(fh)


def combine(cards):
    """Pool scorecards over packs: counts and exposure add up."""
    k = sum(c['detection']['k'] for c in cards)
    n = sum(c['detection']['n'] for c in cards)
    fp = sum(c['noise']['false_alerts'] for c in cards)
    inc = sum(c['noise']['false_incidents'] for c in cards)
    hours = sum(c['exposure']['host_hours'] for c in cards)
    return {'k': k, 'n': n, 'fp': fp, 'fp_incidents': inc, 'hours': hours,
            'rate': fp / hours, 'rate_ci': stats.poisson_rate_ci(fp, hours),
            'ci': stats.wilson(k, n), 'inc_day': inc / hours * 24}


def pct_ci(ci):
    return '%.0f–%.0f%%' % (100 * ci[0], 100 * ci[1])


def rate(value):
    return format(round(value, 1), ',.1f')


def p_text(p):
    return '< 0.0001' if p < 1e-4 else '%.2g' % p


def row_for(engine, label, cards, tuned):
    c = combine(cards)
    return ('| %s%s | **%d / %d** (95%% CI %s) | **%s** (95%% CI %s–%s) | %s |'
            % (label, ' (tuned)' if tuned else '', c['k'], c['n'],
               pct_ci(c['ci']), rate(c['rate']), rate(c['rate_ci'][0]),
               rate(c['rate_ci'][1]), rate(c['inc_day']))), c


def build(runs):
    out = ['# NetWatch Bench results: CSE-CIC-IDS2018', '',
           'Generated by `eval/cicids2018/bench_results.py` from the '
           'scorecards of one run; every number below is in a '
           '`scorecard.json`. Back to [NetWatch Bench]'
           '(../../netwatch_bench/README.md).', '']
    engines = {}
    for key, label in ENGINES:
        raw = [load(os.path.join(runs, 'full', '%s-%s' % (key, p),
                                 'scorecard.json')) for p in HELD_OUT]
        tuned = [load(os.path.join(runs, 'tuned', '%s-%s' % (key, p),
                                   'scorecard.json')) for p in HELD_OUT]
        dev = load(os.path.join(runs, 'full', '%s-dev' % key,
                                'scorecard.json'))
        tuning = load(os.path.join(runs, 'tuned', '%s.tuning.json' % key))
        if all(raw) and dev:
            engines[key] = (label, raw, tuned if all(tuned) else None, dev,
                            tuning)

    out += ['## Held-out traffic (6 attacks, %s host-hours)' % rate(
        combine(next(iter(engines.values()))[1])['hours']), '',
        'Both held-out packs pooled. No engine was tuned on them. "Tuned" '
        'means the engine\'s own suppression list from the development '
        'pack, chosen under the same budget (at most 10 rules, noisiest '
        'first, never a rule that caught an attack).', '',
        '| Engine | Attacks detected | False alerts / host-hour | '
        'False incidents / host-day |', '|---|---|---|---|']
    pooled = {}
    for key, (label, raw, tuned, _dev, _t) in engines.items():
        line, pooled[key] = row_for(key, label, raw, False)
        out.append(line)
        if tuned:
            line, pooled[key + '+tuned'] = row_for(key, label, tuned, True)
            out.append(line)

    out += ['', '### Is the difference real?', '',
            '| Comparison | Detection (Fisher exact) | False alerts '
            '(Poisson rate test) |', '|---|---|---|']
    for suffix, title in (('', 'as distributed'), ('+tuned', 'both tuned')):
        base = pooled.get('netwatch' + suffix)
        for key, (label, *_rest) in engines.items():
            other = pooled.get(key + suffix)
            if key == 'netwatch' or not base or not other:
                continue
            p_det = stats.fisher_exact(base['k'], base['n'], other['k'],
                                       other['n'])
            p_fp = stats.poisson_rate_test(base['fp'], base['hours'],
                                           other['fp'], other['hours'])
            out.append('| NetWatch vs %s, %s | p = %s | p = %s |'
                       % (label, title, p_text(p_det), p_text(p_fp)))

    out += ['', '## Per attack, held-out', '',
            '| Attack | ' + ' | '.join(label for label, *_ in
                                       engines.values()) + ' |',
            '|---|' + '---|' * len(engines)]
    first = next(iter(engines.values()))[1]
    for pack_index, card in enumerate(first):
        for row_index, row in enumerate(card['scenarios']):
            cells = []
            for label, raw, _tuned, _dev, _t in engines.values():
                r = raw[pack_index]['scenarios'][row_index]
                cells.append(('yes: ' + ', '.join(list(r['rules'])[:2])
                              if r['detected'] else '**missed**')[:70])
            out.append('| %s | %s |' % (row['label'], ' | '.join(cells)))

    out += ['', '## Development set (tuned on, so optimistic)', '',
            '| Engine | Attacks detected | False alerts / host-hour |',
            '|---|---|---|']
    for key, (label, _raw, _tuned, dev, tuning) in engines.items():
        out.append('| %s | %d / %d | %s |' % (
            label, dev['detection']['k'], dev['detection']['n'],
            rate(dev['noise']['false_alerts_per_host_hour'])))

    out += ['', '## What each engine suppressed', '']
    for key, (label, _raw, _tuned, _dev, tuning) in engines.items():
        if not tuning:
            continue
        out.append('**%s**: %d rules, removing %s of %s false alerts on the '
                   'development pack.' % (
                       label, len(tuning['rules']),
                       format(tuning['false_alerts_removed_on_tuning_pack'],
                              ','),
                       format(tuning['false_alerts_on_tuning_pack'], ',')))
        out += ['', '| Rule | False alerts on dev |', '|---|---|']
        out += ['| %s | %s |' % (d['name'], format(d['false_alerts'], ','))
                for d in tuning['detail']]
        out.append('')

    out += ['## Read this before quoting a number', '',
            '- **One lab network, six held-out attacks.** Detection '
            'differences of this size are not statistically significant '
            '(see the table above). The noise differences are.',
            '- **The budget is not the same size for everyone.** A NetWatch '
            '"rule" is a whole detector (there are 18); a Suricata rule is '
            'one of tens of thousands of signatures. Ten suppressions remove '
            'more of NetWatch\'s coverage than of Suricata\'s; NetWatch '
            'used fewer than ten because its other noisy detectors also '
            'catch attacks.',
            '- **NetWatch is not untouched even "as distributed".** Its '
            'thresholds were set while developing on the development pack '
            '(docs/real-traffic-validation.md). Suricata and Zeek ran with '
            'their stock configuration and rules.',
            '- **Matching is by addresses, time and technique.** An alert '
            'from the right hosts at the right time counts, whatever its '
            'reason. The per-attack table lists the rules that fired, so '
            'the reader can judge: Suricata\'s infiltration "detection" is '
            'mostly protocol anomaly events, not a signature for the attack.',
            '- **Checksum validation is off** for Suricata, because these '
            'captures were taken with NIC checksum offload (see the '
            'adapter); with it on, one capture alone raises 2.1 million '
            'checksum alerts.', '']
    out += ['## Versions', '', '| Engine | Version | Rules |', '|---|---|---|']
    for key, (label, raw, _tuned, _dev, _t) in engines.items():
        e = raw[0]['manifest']['engine']
        out.append('| %s | %s | %s%s |' % (
            label, e.get('version') or '—', e.get('rules') or 'built in',
            ' (sha256 `%s`)' % e['rules_sha256'][:16]
            if e.get('rules_sha256') else ''))
    return '\n'.join(out) + '\n'


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.split('\n\n')[0])
    ap.add_argument('--runs', default=os.path.join(ROOT, 'runs'))
    ap.add_argument('--out', default=os.path.join(
        ROOT, 'docs', 'bench', 'results-cicids2018.md'))
    args = ap.parse_args(argv)
    text = build(args.runs)
    with open(args.out, 'w', encoding='utf-8') as fh:
        fh.write(text)
    print(text)
    return 0


if __name__ == '__main__':
    sys.exit(main())
